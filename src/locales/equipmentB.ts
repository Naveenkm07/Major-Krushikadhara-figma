/** Translate a leading equipment-type word (e.g. "Tractor (45 HP)") using a lookup map. */
export function localizeName(name: string | undefined, names: Record<string, string>): string {
  if (!name) return ""
  const keys = Object.keys(names).sort((a, b) => b.length - a.length)
  for (const k of keys) {
    if (name === k) return names[k]
    if (name.startsWith(k + " (")) return names[k] + name.slice(k.length)
  }
  return name
}
